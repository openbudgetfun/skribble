/// A point in the drawing's 100 by 100 coordinate space.
typedef DoodlePoint = ({double x, double y});

/// A cubic segment, including its two handles and endpoint.
typedef DoodleCurve = ({
  DoodlePoint first,
  DoodlePoint second,
  DoodlePoint end,
});

/// One continuous stroke. Closed strokes may also receive a wash of color.
class DoodleStroke {
  /// Creates immutable cubic geometry shared by Flutter and vector exports.
  const DoodleStroke(this.start, this.curves, {this.closed = false});

  /// The first point on this stroke.
  final DoodlePoint start;

  /// The ordered cubic segments.
  final List<DoodleCurve> curves;

  /// Whether the final segment returns to the first point.
  final bool closed;

  /// SVG geometry using the same coordinates as the Flutter painter.
  String get svgPath {
    String point(DoodlePoint p) =>
        '${p.x.toStringAsFixed(3)} ${p.y.toStringAsFixed(3)}';

    return 'M ${point(start)} ${curves.map((c) => 'C ${point(c.first)} ${point(c.second)} ${point(c.end)}').join(' ')}${closed ? ' Z' : ''}';
  }
}

/// Generates smooth, repeatable curves without adding short jagged segments.
///
/// A continuous displacement field preserves shared endpoints and closed
/// contours. Amplitude is measured in the drawing's 100-unit coordinate space.
List<DoodleStroke> doodleGeometry(
  WiredDoodleKind kind, {
  int seed = 1,
  double amplitude = 1,
}) {
  final phase = (seed % 65521) * 0.61803398875;

  DoodlePoint point(double x, double y) => (
    x: x + amplitude * math.sin(x * .055 + y * .035 + phase),
    y: y + amplitude * math.sin(y * .045 - x * .025 + phase + 2),
  );

  DoodleStroke stroke(List<double> data, {bool closed = false}) {
    final start = point(data[0], data[1]);
    if ((data.length - 2) % 6 == 0) {
      return DoodleStroke(
        start,
        List.unmodifiable([
          for (var i = 2; i < data.length; i += 6)
            (
              first: point(data[i], data[i + 1]),
              second: point(data[i + 2], data[i + 3]),
              end: point(data[i + 4], data[i + 5]),
            ),
        ]),
        closed: closed,
      );
    }

    // A point sequence is convenient for playful silhouettes with many
    // bends. Convert it to a smooth Catmull–Rom-like cubic path so the
    // public geometry stays continuous even when a shape is authored as
    // hand-drawn points rather than explicit handles.
    var points = [
      for (var i = 0; i + 1 < data.length; i += 2) (x: data[i], y: data[i + 1]),
    ];
    final repeatsStart = points.length > 1 && points.last == points.first;
    if (closed && repeatsStart) points = points.sublist(0, points.length - 1);
    final curves = <DoodleCurve>[];
    final segmentCount = closed ? points.length : points.length - 1;
    for (var i = 0; i < segmentCount; i++) {
      final current = points[i];
      final next = points[(i + 1) % points.length];
      final previous = closed
          ? points[(i - 1 + points.length) % points.length]
          : (i == 0 ? current : points[i - 1]);
      final following = closed
          ? points[(i + 2) % points.length]
          : (i + 2 < points.length ? points[i + 2] : next);
      curves.add((
        first: point(
          current.x + (next.x - previous.x) / 6,
          current.y + (next.y - previous.y) / 6,
        ),
        second: point(
          next.x - (following.x - current.x) / 6,
          next.y - (following.y - current.y) / 6,
        ),
        end: point(next.x, next.y),
      ));
    }
    return DoodleStroke(start, List.unmodifiable(curves), closed: closed);
  }

