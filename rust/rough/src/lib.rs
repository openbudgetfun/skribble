/// Formats `value` with at most `digits` decimals, trimming trailing zeros,
/// exactly as the engine writes SVG coordinates.
///
/// ```
/// assert_eq!(skribble_rough::format_number(0.125, 2), "0.13");
/// assert_eq!(skribble_rough::format_number(4.0, 2), "4");
/// ```
pub fn format_number(value: f64, digits: usize) -> String {
	math::format_number(value, digits)
}
