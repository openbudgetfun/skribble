//! The hand-drawn rendering engine behind skribble, for Rust.
//!
//! It turns ideal geometry into lines that wobble like they were drawn by
//! hand, fills shapes with sketched hachure, dots, dashes, or zig-zags, and
//! lays the result down as pen-shaped ink with tapered ends. It is a Rust port
//! of the Dart package `skribble_rough`, so **the same seed draws the same SVG
//! path data** as skribble's Flutter widgets, its Jaspr components, and the
//! `@skribble.dev/rough` npm package.
//!
//! Most code starts with [`sketch`], which describes a drawing as SVG paths
//! any renderer can paint:
//!
//! ```
//! use skribble_rough::FillStyle;
//! use skribble_rough::Shape;
//! use skribble_rough::SketchOptions;
//! use skribble_rough::sketch;
//!
//! let options = SketchOptions {
//! 	fill: Some("#ffd43b".to_owned()),
//! 	fill_style: Some(FillStyle::CrossHatch),
//! 	..SketchOptions::default()
//! };
//! let badge = sketch(&[Shape::ellipse(50.0, 50.0, 90.0, 90.0)], &options)?;
//! println!("{}", badge.to_svg_string(100.0, 100.0, Some("A sketched badge")));
//! # Ok::<(), skribble_rough::SketchError>(())
//! ```
//!
//! The lower layers are public too: [`Generator`] draws [`Drawable`]s from a
//! [`DrawConfig`] and a [`Filler`], [`RoughSvgPaths`] writes their plain
//! centrelines, and [`DrawableInk`] and [`InkStroke`] give them a
//! [`RoughPen`]'s tapered ink.
//!
//! # Determinism
//!
//! [`Randomizer`] reproduces the Dart VM's `Random(seed)` bit for bit, and the
//! engine follows the Dart code operation for operation, including Dart's
//! rounding and sort order. The tests replay fixtures generated by the Dart
//! engine and expect identical SVG for every shape, fill style, and pen.
//! `sin` and `cos` can differ in their last bit between platforms' maths
//! libraries; that has never shown in the rounded output, but a coordinate
//! that lands exactly on a rounding boundary could print one hundredth
//! differently.

